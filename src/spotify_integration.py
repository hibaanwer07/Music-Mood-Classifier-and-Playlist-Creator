# 🎶 Helper: Get Spotify recommendations
# ------------------------------------------------------------
def get_spotify_recommendations(mood, limit=10):
    sp = spotify_authenticate()
    if not sp:
        return []

    # Map mood to seed genres or tracks
    mood_seeds = { 
        'happy': {'seed_genres': ['pop'], 'target_valence': 0.8, 'target_energy': 0.8},
        'sad': {'seed_genres': ['indie'], 'target_valence': 0.2, 'target_energy': 0.3},
        'energetic': {'seed_genres': ['rock'], 'target_valence': 0.7, 'target_energy': 0.9},
        'calm': {'seed_genres': ['ambient'], 'target_valence': 0.5, 'target_energy': 0.2}
    } 

    seeds = mood_seeds.get(mood.lower(), mood_seeds['happy'])

    try:
        recommendations = sp.recommendations(
            seed_genres=seeds['seed_genres'],
            limit=limit,
            target_valence=seeds['target_valence'],
            target_energy=seeds['target_energy']
        )
        tracks = []
        for track in recommendations['tracks']:
            tracks.append({
                'name': track['name'],
                'artist': track['artists'][0]['name'],
                'url': track['external_urls']['spotify']
            })
        return tracks
    except Exception as e:
        st.error(f"Error getting recommendations: {e}")
        return []

