SPOTIFY_CLIENT_ID = os.getenv("SPOTIFY_CLIENT_ID", "b0e32a2636ac44a699844f06637a573e").strip()
SPOTIFY_CLIENT_SECRET = os.getenv("SPOTIFY_CLIENT_SECRET", "63885723876f4a25a247fb294a5e92a8").strip()
SPOTIFY_REDIRECT_URI = os.getenv("SPOTIFY_REDIRECT_URI", "http://localhost:8502/callback").strip()

# ------------------------------------------------------------
# 🚨 Validate credentials
# ------------------------------------------------------------
if not all([SPOTIFY_CLIENT_ID, SPOTIFY_CLIENT_SECRET, SPOTIFY_REDIRECT_URI]): 
    st.error("Missing Spotify credentials. Please update `.env` or hardcode values.")
    st.stop()

# ------------------------------------------------------------
# ⚙️ Spotify OAuth configuration
# ------------------------------------------------------------
def get_spotify_oauth(): # Configure Spotify OAuth
    return SpotifyOAuth(
        client_id=SPOTIFY_CLIENT_ID,
        client_secret=SPOTIFY_CLIENT_SECRET,
        redirect_uri=SPOTIFY_REDIRECT_URI,
        scope="playlist-modify-public playlist-modify-private user-library-read",
        cache_path=".cache",
        show_dialog=True
    )

# ------------------------------------------------------------
# 🔄 Refresh token automatically
# ------------------------------------------------------------
def refresh_spotify_token(): # Refresh Spotify token if expired
    token_info = st.session_state.get("spotify_token")
    if not token_info:
        return None

    now = int(time.time())
    if token_info["expires_at"] - now < 60:
        sp_oauth = get_spotify_oauth()
        try:
            token_info = sp_oauth.refresh_access_token(token_info["refresh_token"])
            st.session_state.spotify_token = token_info
            st.success("🔁 Spotify token refreshed successfully.")
        except SpotifyOauthError as e:
            st.error(f"Failed to refresh token: {e}")
            st.session_state.spotify_token = None
            return None
    return token_info

# ------------------------------------------------------------
# 🎟️ Spotify Authentication Flow
# ------------------------------------------------------------
def spotify_authenticate(): # Authenticate user with Spotify
    if "spotify_token" not in st.session_state:
        st.session_state.spotify_token = None

    sp_oauth = get_spotify_oauth()

    # If user hasn’t authenticated yet
    if not st.session_state.spotify_token:
        auth_url = sp_oauth.get_authorize_url()
        st.markdown(f"👉 [Click here to authenticate with Spotify]({auth_url})")
        st.info("After logging in, you’ll be redirected back to the app automatically.")
        return None

    # Refresh token if expired
    token_info = refresh_spotify_token()
    if not token_info:
        return None

    # Create Spotify client
    try:
        sp = spotipy.Spotify(auth=token_info["access_token"])
        user = sp.current_user()
        st.success(f"🎧 Logged in as: **{user['display_name']}**")
        return sp
    except Exception as e:
        st.error(f"Spotify authentication failed: {e}")
        st.session_state.spotify_token = None
        return None

# ------------------------------------------------------------
# 🎶 Helper: Check if playlist exists
# ------------------------------------------------------------
def get_playlist_id(sp, playlist_name): 
    user_id = sp.current_user()["id"]
    playlists = sp.user_playlists(user_id)
    for playlist in playlists["items"]:
        if playlist["name"] == playlist_name:
            return playlist["id"]
    return None

# ------------------------------------------------------------
# 🎶 Helper: Create playlist
# ------------------------------------------------------------
def create_playlist(sp, playlist_name, public=False, description="Generated by Streamlit App"):
    user_id = sp.current_user()["id"]
    playlist = sp.user_playlist_create(user=user_id, name=playlist_name, public=public, description=description)
    return playlist["id"]

# ------------------------------------------------------------
# 🎶 Helper: Add tracks to playlist
# ------------------------------------------------------------
def add_tracks_to_playlist(sp, playlist_name, track_ids):
    playlist_id = get_playlist_id(sp, playlist_name)
    if not playlist_id:
        playlist_id = create_playlist(sp, playlist_name)
        st.success(f"🎶 Playlist '{playlist_name}' created.")

    if track_ids:
        sp.playlist_add_items(playlist_id, track_ids)
        st.success(f"✅ Added {len(track_ids)} tracks to '{playlist_name}'")
    else:
        st.warning("⚠️ No track IDs provided to add.")

