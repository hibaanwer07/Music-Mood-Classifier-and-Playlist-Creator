def add_track_to_playlist(mood, track_uris):
    sp = spotify_authenticate()
    if not sp:
        return

    playlist_name = f"{mood.capitalize()} Mood Playlist"
    playlist_id = get_playlist_id(sp, playlist_name)
    if not playlist_id:
        playlist_id = create_playlist(sp, playlist_name)

    if isinstance(track_uris, str):
        track_uris = [track_uris]

    if track_uris:
        sp.playlist_add_items(playlist_id, track_uris)
        st.success(f"✅ Added {len(track_uris)} tracks to '{playlist_name}'")
    else:
        st.warning("⚠️ No track URIs provided to add.")

