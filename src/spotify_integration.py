# ------------------------------------------------------------
# 🎶 Helper: Get playlist tracks
# ------------------------------------------------------------
def get_playlist_tracks(mood):
    sp = spotify_authenticate()
    if not sp:
        return []

    playlist_id = create_or_get_playlist(mood)
    if not playlist_id:
        return []

    try:
        results = sp.playlist_tracks(playlist_id)
        tracks = []
        for item in results['items']:
            track = item['track']
            tracks.append({
                'name': track['name'],
                'artist': track['artists'][0]['name'],
                'url': track['external_urls']['spotify']
            })
        return tracks
    except Exception as e:
        st.error(f"Error getting playlist tracks: {e}")
        return []

